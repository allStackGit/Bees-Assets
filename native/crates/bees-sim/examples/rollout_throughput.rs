//! Native combat-world movement/physics throughput baseline.
//!
//! Run on Linux or Windows with a release build:
//! cargo run --release --manifest-path native/Cargo.toml -p bees-sim \
//!     --example rollout_throughput -- --worlds 16 --ships 2 --steps 1000 --workers 4
//!
//! This fixture uses real authored Wasp/Gunship hulls and the shared
//! CombatWorld physics, but deliberately disables collision layers and does
//! not fire weapons or run neural inference. The imported Unity collision
//! matrix and full game Level adapter are not yet available. Never present
//! these numbers as combat parity or end-to-end Bees training throughput.

use std::env;
use std::num::{NonZeroU32, NonZeroUsize};
use std::sync::Arc;

use bees_sim::collision::Aabb;
use bees_sim::combat::ShipVitals;
use bees_sim::combat_world::{CombatWorld, CombatWorldRules};
use bees_sim::geometry::Vec2;
use bees_sim::movement::ShipMotion;
use bees_sim::physics::CollisionMatrix;
use bees_sim::policy::Decision;
use bees_sim::projectile_assets::ProjectileAssetCatalog;
use bees_sim::ship_assets::ShipAssetCatalog;
use bees_sim::simulation::{Simulation, World, WorldId};

#[derive(Clone, Copy)]
struct Options {
    worlds: usize,
    ships: usize,
    steps: u32,
    workers: usize,
    /// Every fourth world can use a heavier authentic-hull population.
    /// Other worlds retain --ships, allowing mixed 1v1 and fleet load.
    heavy_ships: Option<usize>,
}

impl Default for Options {
    fn default() -> Self {
        Self { worlds: 16, ships: 2, steps: 1000, workers: 4, heavy_ships: None }
    }
}

fn options() -> Options {
    let mut opt = Options::default();
    let mut arguments = env::args().skip(1);
    while let Some(flag) = arguments.next() {
        if flag == "--help" || flag == "-h" {
            println!("Usage: rollout_throughput [--worlds 1..256] [--ships 1..256] [--steps 1..1000000] [--workers 1..128] [--heavy-ships 1..256]");
            std::process::exit(0);
        }
        let value = arguments.next().unwrap_or_else(|| panic!("missing value for {flag}"));
        let parsed: usize = value.parse().unwrap_or_else(|_| panic!("invalid value for {flag}: {value}"));
        match flag.as_str() {
            "--worlds" if (1..=256).contains(&parsed) => opt.worlds = parsed,
            "--ships" if (1..=256).contains(&parsed) => opt.ships = parsed,
            "--steps" if (1..=1_000_000).contains(&parsed) => opt.steps = parsed as u32,
            "--workers" if (1..=128).contains(&parsed) => opt.workers = parsed,
            "--heavy-ships" if (1..=256).contains(&parsed) => opt.heavy_ships = Some(parsed),
            _ => panic!("unknown option or value out of range: {flag}={value}"),
        }
    }
    opt
}

fn build_worlds(
    opt: Options,
    assets: &ShipAssetCatalog,
    projectiles: &Arc<ProjectileAssetCatalog>,
) -> Simulation<CombatWorld, CombatWorldRules> {
    // No permissive matrix may enter the real game. This benchmark disables
    // collisions explicitly and is only a physics/movement baseline.
    let rules = CombatWorldRules {
        collision_matrix: CollisionMatrix::from_rows([0; 32]),
    };
    let mut sim = Simulation::new(rules, 0.02).expect("valid fixed timestep");
    sim.set_timing_sample_period(NonZeroU32::new(128));

    for world_index in 0..opt.worlds {
        let ships = if world_index % 4 == 0 {
            opt.heavy_ships.unwrap_or(opt.ships)
        } else {
            opt.ships
        };
        let columns = (ships as f32).sqrt().ceil() as usize;
        let half_extent = (columns as f32 * 16.0) / 2.0 + 128.0;
        let mut world = CombatWorld::new(
            Aabb {
                min: Vec2::new(-half_extent, -half_extent),
                max: Vec2::new(half_extent, half_extent),
            },
            8.0,
            Arc::clone(projectiles),
        ).expect("valid benchmark arena");
        for index in 0..ships {
            let kind = if index % 2 == 0 { 21 } else { 13 };
            let ship = assets.by_type(kind).expect("authored Wasp/Gunship hull");
            let x = ((index % columns) as f32 - (columns as f32 - 1.0) * 0.5) * 16.0;
            let y = ((index / columns) as f32 - (columns as f32 - 1.0) * 0.5) * 16.0;
            let mut motion = ShipMotion::new(
                Vec2::new(x, y), 0.0, 0.0, 10.0, 3.0,
            );
            // Motion is given directly, not generated by a fake policy.
            motion.body_velocity = Vec2::new(if index % 2 == 0 { 1.0 } else { -1.0 }, 0.0);
            world.spawn_ship(
                ship,
                (index + 1) as i64,
                if index % 2 == 0 { 1 } else { 2 },
                ShipVitals::new(100, 100, 1000, 0).expect("valid ship health"),
                motion,
            ).expect("valid real-hull ship spawn");
        }
        sim.add_world(World::new(
            WorldId((world_index + 1) as u64),
            0xbee5_2026_u64 + world_index as u64,
            world,
        )).expect("unique arena");
    }
    sim
}

/// Stable, noncryptographic state fingerprint, computed only AFTER the
/// timed window. This catches divergent world poses/RNG/vitals between
/// serial and parallel execution of the same real native physics rules.
fn fingerprint(sim: &Simulation<CombatWorld, CombatWorldRules>) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325_u64;
    let mut absorb = |word: u64| {
        hash = (hash ^ word).wrapping_mul(0x0000_0100_0000_01b3);
    };
    for index in 0..sim.world_count() {
        let world = sim.world(index).expect("existing world");
        absorb(world.id.0);
        absorb(world.tick());
        absorb(world.random.state());
        for body in world.state.physics().ships() {
            absorb(body.id as u64);
            absorb(u64::from(body.motion.position.x.to_bits()));
            absorb(u64::from(body.motion.position.y.to_bits()));
            absorb(u64::from(body.motion.rotation_degrees.to_bits()));
            absorb(u64::from(body.motion.current_speed.to_bits()));
            absorb(if body.active { 1 } else { 0 });
        }
        for ship in world.state.ships() {
            absorb(ship.entity_id as u64);
            absorb(ship.vitals.health() as u64);
        }
    }
    hash
}

fn measure(
    opt: Options,
    workers: usize,
    label: &str,
    assets: &ShipAssetCatalog,
    projectiles: &Arc<ProjectileAssetCatalog>,
) -> (u64, u64, u64, u64, u64, u64) {
    let mut sim = build_worlds(opt, assets, projectiles);
    let no_policy_actions = |_: &World<CombatWorld>, _: &mut Vec<Decision>| {};
    // Same unmeasured warm-up in both configurations.
    let warm = sim.run_parallel_window(
        NonZeroU32::new(20).unwrap(),
        NonZeroUsize::new(workers).unwrap(),
        &no_policy_actions,
    );
    assert!(warm.failed_worlds.is_empty(), "benchmark warm-up failed");

    let report = sim.run_parallel_window(
        NonZeroU32::new(opt.steps).unwrap(),
        NonZeroUsize::new(workers).unwrap(),
        &no_policy_actions,
    );
    assert!(report.failed_worlds.is_empty(), "native physics step failed");
    let m = report.measurements;
    println!(
        "{label},{},{},{workers},{},{:.3},{:.1},{},{},{},{},{}",
        opt.worlds, opt.ships, m.ticks,
        report.wall_elapsed.as_secs_f64(),
        report.steps_per_second().unwrap_or(0.0),
        m.integrated_bodies, m.broadphase_candidates,
        m.narrowphase_tests, m.trigger_enters,
        opt.heavy_ships.unwrap_or(0),
    );
    eprintln!("{label} CPU worker loads (arenas, steps, bodies, narrowphase): {:?}",
        report.worker_loads);
    (fingerprint(&sim), m.ticks, m.integrated_bodies,
        m.broadphase_candidates, m.narrowphase_tests, m.trigger_enters)
}

fn main() {
    let opt = options();
    eprintln!("PHYSICS BASELINE ONLY: authored ship hulls, no weapons, no AI, collision layers disabled; not full gameplay/training TPS.");
    let assets = ShipAssetCatalog::embedded().expect("authored ship collider catalog");
    let projectiles = Arc::new(
        ProjectileAssetCatalog::embedded().expect("authored projectile collider catalog"),
    );
    println!("mode,worlds,ships_per_world,workers,world_steps,wall_seconds,world_steps_per_second,integrated_bodies,broadphase_candidates,narrowphase_tests,contacts,heavy_ships_every_fourth_world");
    let serial = measure(opt, 1, "serial", &assets, &projectiles);
    let parallel = measure(opt, opt.workers, "parallel", &assets, &projectiles);
    assert_eq!(
        serial, parallel,
        "serial and parallel native physics state/workload differed",
    );
    eprintln!("State, RNG and physics workload parity: verified for this baseline fixture.");
}
